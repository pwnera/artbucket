/** A name as an address segment: "Press kit" is press-kit. lib/catalog.ts slugOf, as SQL. */
const slugSql = (name: string) => sql.raw(`trim(both '-' from regexp_replace(lower(${name}), '[^a-z0-9]+', '-', 'g'))`);

/**
 * Every object a person or an agent can find, in one shape (lib/core/catalog.ts,
 * PRD: Artbucket Catalog): assets, collections, brands and portals, and the
 * parts of a brand (its rules and pages), each with its workspace, an address
 * segment (`slug`), a status on one lifecycle (lib/catalog.ts STATUSES) and a
 * search vector. A view, so nothing is written twice; an asset's vector is its
 * indexed column, the rest are small enough to read as they are.
 *
 * ponytail: an asset's slug comes from its filename, so two files named alike
 * share one and an address picks the newest; store a unique slug if that bites.
 */
export const catalogObjects = pgView("catalog_objects", {
  id: uuid("id").notNull(),
  type: text("type").$type<"asset" | "collection" | "brand" | "portal" | "rule" | "page">().notNull(),
  workspaceId: uuid("workspace_id").notNull(),
  /** A part's object: a rule's or a page's brand. */
  parentId: uuid("parent_id"),
  slug: text("slug").notNull(),
  name: text("name").notNull(),
  description: text("description"),
  status: text("status").$type<"draft" | "in_review" | "current" | "replaced" | "archived">().notNull(),
  /** An asset's version in its stack, a brand's latest release. */
  release: integer("release"),
  /** The last day an asset may be used (lib/rights.ts). */
  expires: text("expires"),
  /** Only grants on it reach it (lib/access.ts): an asset's own flag, or every collection it is in. */
  private: boolean("private").notNull(),
  /** An asset's collections. */
  collections: uuid("collections").array().notNull(),
  tags: jsonb("tags").$type<string[]>().notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull(),
  search: tsvector("search").notNull(),
}).as(
  sql`select a.id, 'asset' as type, a.workspace_id, null::uuid as parent_id,
      coalesce(nullif(${slugSql("regexp_replace(a.filename, '\\.[^.]*$', '')")}, ''), a.id::text) as slug,
      a.filename as name, a.metadata ->> 'description' as description,
      case when a.status = 'draft' then 'draft' when a.status = 'proposed' then 'in_review'
        when a.status in ('archived', 'rejected') then 'archived'
        when a.superseded_by is not null or (a.stack_id is not null and not a.current) then 'replaced'
        else 'current' end as status,
      a.version as release, a.rights ->> 'expires' as expires,
      (a.private or (exists (select 1 from ${collectionAssets} ca where ca.asset_id = a.id)
        and not exists (select 1 from ${collectionAssets} ca join ${collections} c on c.id = ca.collection_id where ca.asset_id = a.id and not c.private))) as private,
      coalesce((select array_agg(ca.collection_id) from ${collectionAssets} ca where ca.asset_id = a.id), '{}'::uuid[]) as collections,
      a.tags, a.created_at, a.updated_at, a.search
    from ${assets} a where a.deleted_at is null
    union all
    select c.id, 'collection', c.workspace_id, null, ${slugSql("c.name")}, c.name, null, 'current', null, null, c.private, '{}'::uuid[], '[]'::jsonb,
      c.created_at, c.created_at, to_tsvector('simple', c.name)
    from ${collections} c
    union all
    select b.id, 'brand', b.workspace_id, null, b.slug, b.name, null,
      case when r.number is null then 'draft' else 'current' end, r.number, null, false, '{}'::uuid[], '[]'::jsonb,
      b.created_at, coalesce(u.at, b.created_at), to_tsvector('simple', b.name || ' ' || b.slug || ' ' || coalesce(b.domain, ''))
    from ${brands} b
    left join lateral (select max(v.number) as number from ${brandVersions} v where v.brand_id = b.id and v.published_at is not null) r on true
    left join lateral (select max(v.updated_at) as at from ${brandVersions} v where v.brand_id = b.id) u on true
    union all
    select p.id, 'portal', p.workspace_id, null, p.slug, p.name, p.intro,
      case when p.expires_at < now() then 'archived' else 'current' end, null, null, false, '{}'::uuid[], '[]'::jsonb,
      p.created_at, p.updated_at, to_tsvector('simple', p.name || ' ' || p.slug || ' ' || coalesce(p.intro, ''))
    from ${portals} p
    union all
    select r.id, 'rule', b.workspace_id, b.id, r.key, coalesce(r.label, r.key), r.usage, 'current', null, null, false, '{}'::uuid[], '[]'::jsonb,
      r.created_at, r.updated_at, to_tsvector('simple', regexp_replace(r.key, '[._-]+', ' ', 'g') || ' ' || coalesce(r.label, '') || ' ' || coalesce(r.usage, ''))
    from ${brandRules} r join ${brands} b on b.id = r.brand_id where r.context is null
    union all
    select g.id, 'page', b.workspace_id, b.id, g.slug, g.title, g.lede, 'current', null, null, false, '{}'::uuid[], '[]'::jsonb,
      g.created_at, g.updated_at, to_tsvector('simple', g.title || ' ' || coalesce(g.eyebrow, '') || ' ' || coalesce(g.lede, ''))
    from ${brandPages} g join ${brands} b on b.id = g.brand_id`,
);

/**
 * What uses what, upstream to downstream (lib/core/catalog.ts lineage), from
 * links the tables already hold: an asset to what replaced it and to what was
 * made from it, to the brands whose rules name it (`via`: their keys) and the
 * collections it is in; a collection or a brand to the portals that offer it;
 * a brand to the brands forked from it.
 */
export const catalogEdges = pgView("catalog_edges", {
  fromId: uuid("from_id").notNull(),
  toId: uuid("to_id").notNull(),
  kind: text("kind").$type<"replaced_by" | "derived" | "rule" | "member" | "offered" | "fork">().notNull(),
  via: text("via"),
}).as(
  sql`select a.id as from_id, a.superseded_by as to_id, 'replaced_by' as kind, null as via from ${assets} a where a.superseded_by is not null
    union all
    select a.parent_asset_id, a.id, 'derived', null from ${assets} a where a.parent_asset_id is not null
    union all
    select bra.asset_id, r.brand_id, 'rule', string_agg(distinct r.key, ', ') from ${brandRuleAssets} bra join ${brandRules} r on r.id = bra.rule_id group by bra.asset_id, r.brand_id
    union all
    select ca.asset_id, ca.collection_id, 'member', null from ${collectionAssets} ca
    union all
    select pc.collection_id, pc.portal_id, 'offered', null from ${portalCollections} pc
    union all
    select pb.brand_id, pb.portal_id, 'offered', null from ${portalBrands} pb
    union all
    select s.id, b.id, 'fork', b.forked_from from ${brands} b
      join ${organizations} o on o.slug = split_part(b.forked_from, '/', 1)
      join ${workspaces} w on w.organization_id = o.id
      join ${brands} s on s.workspace_id = w.id and s.slug = split_part(split_part(b.forked_from, '/', 2), '@', 1)
    where b.forked_from is not null`,
);
