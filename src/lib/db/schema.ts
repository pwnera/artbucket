const tsvector = customType<{ data: string }>({ dataType: () => "tsvector" });

/**
 * Assets are content-addressed: `sha256` is the identity of the bytes, and the
 * storage key is derived from it. Uploading the same file twice is a no-op.
 *
 */
export const assets = pgTable(
  "assets",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    workspaceId: uuid("workspace_id")
      .notNull()
      .references((): AnyPgColumn => workspaces.id, { onDelete: "cascade" }),
    /** Unique within a workspace. Storage is keyed by it alone, so workspaces share identical bytes. */
    sha256: text("sha256").notNull(),
    filename: text("filename").notNull(),
    mime: text("mime").notNull(),
    size: integer("size").notNull(),
    /** Only people with a grant on it (or a collection it is in) and admins see it (lib/access.ts). */
    private: boolean("private").notNull().default(false),
    /**
     * Served at /a/{id} to anyone, for embedding, while it may be used
     * (lib/lifecycle.ts). Otherwise only people who can see it, and holders of
     * a signed URL (lib/signed.ts), get the bytes.
     */
    public: boolean("public").notNull().default(false),
    width: integer("width"),
    height: integer("height"),
    /** Freeform probe output (format, pages, colour space). */
    probe: jsonb("probe").$type<Record<string, unknown>>(),
    /** EXIF / IPTC / XMP read from the file on ingest. See lib/metadata.ts. */
    metadata: jsonb("metadata").$type<Metadata>(),
    /** Lowercased and deduped by lib/tags.ts before they get here. */
    tags: jsonb("tags").$type<string[]>().notNull().default([]),
    /** Values for the library's custom fields, keyed by `fields.key`. */
    fields: jsonb("fields").$type<FieldValues>().notNull().default({}),
    /**
     * Values this asset inherits from its collections, materialized by
     * lib/core/collections.ts whenever membership or a collection changes, so
     * search and filters read one row. The asset's own `fields` win over these.
     */
    inherited: jsonb("inherited").$type<FieldValues>().notNull().default({}),
    /**
     * Where it is in its lifecycle (lib/lifecycle.ts): `draft`, `proposed` (in
     * review) until a human promotes it, which is what a propose-scoped key (an
     * agent) uploads, `active` (approved), `archived`, `rejected`. Expired is
     * derived from `rights`. Default searches show approved, unexpired assets.
     */
    status: text("status").$type<AssetStatus>().notNull().default("active"),
    /**
     * Who proposed it: the API key's name, or "web". Kept after review, so a
     * person sees who sent what and an agent can find its own proposals.
     */
    proposedBy: text("proposed_by"),
    /**
     * Why a person rejected it. A rejected asset is kept, out of the library
     * and the review queue, so the agent that proposed it can read the reason.
     */
    reviewNote: text("review_note"),
    /** Tags an agent suggested, waiting for a human to accept or dismiss. */
    proposedTags: jsonb("proposed_tags").$type<string[]>().notNull().default([]),
    /** Custom field values an agent suggested, keyed like `fields`, waiting for a human to accept or dismiss. */
    proposedFields: jsonb("proposed_fields").$type<FieldValues>().notNull().default({}),
    /** License, territories, channels, embargo, expiry, model release (lib/rights.ts); null says nothing. */
    rights: jsonb("rights").$type<Rights>(),
    /** How it came to be: shot, licensed, or generated by a model. */
    origin: text("origin").$type<Origin>(),
    /** What it was made from: the photo an edit started from, the image a model was given. */
    parentAssetId: uuid("parent_asset_id").references((): AnyPgColumn => assets.id, { onDelete: "set null" }),
    /** The tool or model that made it, e.g. "gpt-image 2.0". */
    generator: text("generator"),
    prompt: text("prompt"),
    /** C2PA Content Credentials read on ingest (lib/c2pa.ts); the original keeps the manifest itself. */
    c2pa: jsonb("c2pa").$type<C2pa>(),
    /**
     * How it arrived, when not from a person: `agent`, through an API key;
     * `import`, brought in from outside by the server (an icon set, Google
     * Fonts, a template). The review queue's chips read it.
     */
    via: text("via").$type<"agent" | "import">(),
    /** The asset that replaces this one. /api/v1/check refuses a replaced asset and names this. */
    supersededBy: uuid("superseded_by").references((): AnyPgColumn => assets.id, { onDelete: "set null" }),
    /**
     * Versions of one thing share a stack: the id of the asset it started
     * from, kept as a plain value so the stack outlives that asset. Null for
     * an asset with one version (lib/core/versions.ts).
     */
    stackId: uuid("stack_id"),
    /** 1, 2, 3 within the stack. */
    version: integer("version"),
    /**
     * The stack's current approved version: the one the library shows, share
     * links serve, and every other approved version is superseded by.
     */
    current: boolean("current").notNull().default(false),
    /**
     * Deleted, and restorable until lib/core/sweep.ts purges it 30 days on.
     * Its bytes stay until then; it reads `state: "deleted"` and is served to nobody.
     */
    deletedAt: timestamp("deleted_at", { withTimezone: true }),
    /**
     * Maintained by Postgres, so it cannot drift from the columns it indexes.
     * 'simple' rather than 'english': asset search is names and keywords, where
     * stemming "logos" to "logo" matters less than matching "fox_v3" by "fox".
     * Filenames are split on . _ - first, since the parser keeps "fox_v3.png"
     * as one token.
     */
    search: tsvector("search")
      .notNull()
      .generatedAlwaysAs(
        sql`setweight(to_tsvector('simple', regexp_replace(filename, '[._-]+', ' ', 'g')), 'A') || setweight(to_tsvector('simple', tags), 'A') || setweight(jsonb_to_tsvector('simple', coalesce(metadata, '{}'), '["string"]'), 'B') || setweight(jsonb_to_tsvector('simple', fields || inherited, '["string"]'), 'B')`,
      ),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .default(sql`now()`),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .default(sql`now()`),
  },
  (t) => [
    unique("assets_workspace_sha256_unique").on(t.workspaceId, t.sha256),
    index("assets_workspace_created_at_idx").on(t.workspaceId, t.createdAt.desc()),
    // Whether anything still holds some bytes, across workspaces: the sweeper asks.
    index("assets_sha256_idx").on(t.sha256),
    index("assets_deleted_at_idx").on(t.deletedAt).where(sql`${t.deletedAt} is not null`),
    index("assets_search_idx").using("gin", t.search),
    index("assets_tags_idx").using("gin", sql`${t.tags} jsonb_path_ops`),
    // Field filters match the effective value, own over inherited: `inherited || fields`.
    index("assets_effective_fields_idx").using("gin", sql`(${t.inherited} || ${t.fields}) jsonb_path_ops`),
    check("assets_status_check", sql`${t.status} in ('draft', 'proposed', 'active', 'archived', 'rejected')`),
    index("assets_proposed_by_idx").on(t.proposedBy),
    check("assets_origin_check", sql`${t.origin} in ('shot', 'licensed', 'generated')`),
    check("assets_via_check", sql`${t.via} in ('agent', 'import')`),
    check("assets_not_superseded_by_self", sql`${t.supersededBy} <> ${t.id}`),
    unique("assets_stack_version_unique").on(t.stackId, t.version),
    uniqueIndex("assets_one_current").on(t.stackId).where(sql`${t.current}`),
    check("assets_stacked_check", sql`(${t.stackId} is null) = (${t.version} is null)`),
  ],
);

